'use strict';
const assert = require('node:assert/strict'), vm = require('node:vm'), fs = require('node:fs');
const {reviewRoute, reviewStatus} = require('../webapp/app.js');
assert.deepEqual(reviewRoute('#video-review?experiment=EXP-0044'), {isReview:true,experimentId:'EXP-0044'});
assert.equal(reviewRoute('#video-review?experiment=../../etc/passwd').experimentId,null);
assert.equal(reviewRoute('#history').isReview,false);
assert.equal(reviewStatus(null).kind,'none');
assert.equal(reviewStatus(null,false).kind,'unknown');
assert.equal(reviewStatus({total:2,pending:1,applied:1}).kind,'pending');
assert.equal(reviewStatus({total:1,answered:1}).kind,'answered');
assert.equal(reviewStatus({total:1,acknowledged:1}).kind,'acknowledged');
assert.equal(reviewStatus({total:1,applied:1}).kind,'applied');
assert.equal(reviewStatus({total:2,applied:1,deferred:1}).kind,'deferred');
const calls = [];
const video = {pause() { calls.push('pause'); }};
const history = {hidden:false, querySelectorAll:() => [video]};
const review = {hidden:true, querySelectorAll:() => [video]};
const links = ['history'].map(route => ({dataset:{route}, setAttribute(k,v){this[k]=v;}, removeAttribute(k){delete this[k];}}));
const ctx = vm.createContext({location:{hash:''},URLSearchParams});
vm.runInContext(fs.readFileSync('webapp/app.js','utf8'),ctx);
ctx.document = {querySelector:s => s === '#history-page' ? history : review, querySelectorAll:() => links};
vm.runInContext('loadReviewPage = id => { requested = id; }; setRoute()',ctx);
assert.equal(history.hidden,false); assert.equal(review.hidden,true); assert.equal(links[0]['aria-current'],'page');
ctx.location.hash='#video-review?experiment=EXP-0044'; vm.runInContext('setRoute()',ctx);
assert.equal(history.hidden,true); assert.equal(review.hidden,false); assert.equal(links[0]['aria-current'],undefined);
assert.equal(ctx.requested,'EXP-0044'); assert.equal(calls.length,2);
console.log('scoped review route, invalid ID, request states, active navigation and hidden media pause passed');
